/// Isobar block from Table A-6: Superheated water.
class SuperheatedIsobar {
  const SuperheatedIsobar({
    required this.pMpa,
    required this.tSat,
    required this.hgSat,
    required this.points,
  });

  /// Pressure in MPa (1 MPa = 10 bar = 1000 kPa).
  final double pMpa;

  /// Saturation temperature T_sat in °C at [pMpa].
  final double tSat;

  /// Saturated vapour enthalpy h_g in kJ/kg at [pMpa].
  final double hgSat;

  /// Superheated enthalpy points `(T in °C, h in kJ/kg)`.
  final List<(double tC, double h)> points;

  /// Enthalpy h(T) at this isobar for T >= [tSat], linearly interpolated
  /// between the Table A-6 temperature rows (starting from `(tSat, hgSat)`).
  double enthalpyAt(double tempC) {
    if (tempC <= tSat) return hgSat;
    var prevT = tSat;
    var prevH = hgSat;
    for (final (t, h) in points) {
      if (tempC <= t) {
        final frac = (tempC - prevT) / (t - prevT);
        return prevH + frac * (h - prevH);
      }
      prevT = t;
      prevH = h;
    }
    // Linear extrapolation above 1300 °C if needed.
    if (points.length >= 2) {
      final (t0, h0) = points[points.length - 2];
      final (t1, h1) = points.last;
      final slope = (h1 - h0) / (t1 - t0);
      return h1 + slope * (tempC - t1);
    }
    return prevH;
  }
}

